def main() -> None:
    """Run weekly report generation and write markdown + CSV artifacts."""
    args = parse_args()

    required_paths = [args.analysis_dataset, args.symbol_log, args.candidate_log]
    for path in required_paths:
        if not path.exists():
            raise FileNotFoundError(f"Required input file not found: {path}")

    reason_summary_path = (
        args.reports_dir / f"{args.rejection_prefix}_reason_summary.csv"
    )
    bucket_summary_path = (
        args.reports_dir / f"{args.rejection_prefix}_bucket_summary.csv"
    )
    for path in (reason_summary_path, bucket_summary_path):
        if not path.exists():
            raise FileNotFoundError(
                "Missing rejection diagnostics export: "
                f"{path}. Run analysis/rejection_diagnostics.py first."
            )

    start_date = parse_iso_date(args.start_date)
    end_date = parse_iso_date(args.end_date)
    if args.start_date and start_date is None:
        raise ValueError("Invalid --start-date. Expected format YYYY-MM-DD.")
    if args.end_date and end_date is None:
        raise ValueError("Invalid --end-date. Expected format YYYY-MM-DD.")
    if start_date and end_date and start_date > end_date:
        raise ValueError("--start-date cannot be after --end-date.")

    dataset_header, analysis_rows_all = load_csv_rows(args.analysis_dataset)
    if not dataset_header:
        raise ValueError("Analysis dataset is empty or missing a header.")

    analysis_rows = filter_rows_by_date(
        analysis_rows_all,
        args.dataset_date_column,
        start_date,
        end_date,
    )
    closed_trade_rows = filter_rows_by_date(
        analysis_rows_all,
        "close_date",
        start_date,
        end_date,
    )
    selected_rows = [row for row in analysis_rows if as_bool(row.get("selected", ""))]

    symbol_header, symbol_rows = load_csv_rows(args.symbol_log)
    _, candidate_rows = load_csv_rows(args.candidate_log)
    symbol_rows = filter_rows_by_date(
        symbol_rows,
        args.symbol_date_column,
        start_date,
        end_date,
    )
    candidate_rows = filter_rows_by_date(
        candidate_rows,
        args.candidate_date_column,
        start_date,
        end_date,
    )

    closed_records = build_closed_trade_records(closed_trade_rows)
    overall = summarize_performance(closed_records)

    rolling_window_metrics = build_rolling_window_metrics(closed_records)
    rolling_rejection_trends = build_rolling_rejection_trends(
        symbol_rows,
        candidate_rows,
        args.symbol_date_column,
        args.candidate_date_column,
    )
    rolling_rejection_reason_trends = build_rolling_rejection_reason_trends(
        candidate_rows,
        symbol_rows,
        args.candidate_date_column,
        args.symbol_date_column,
    )

    segment_rows = {
        "symbol": build_segment_summaries(
            closed_records,
            lambda row: (row.get("symbol") or "").strip() or "(missing)",
            args.top_n,
        ),
        "strategy_version": build_segment_summaries(
            closed_records,
            lambda row: (row.get("strategy_version") or "").strip() or "(missing)",
            args.top_n,
        ),
        "width": build_segment_summaries(
            closed_records,
            lambda row: normalize_width(row.get("width", "")),
            args.top_n,
        ),
        "dte_band": build_segment_summaries(
            closed_records,
            lambda row: dte_band(row.get("dte", "")),
            args.top_n,
        ),
        "delta_band": build_segment_summaries(
            closed_records,
            lambda row: delta_band(row.get("short_delta", "")),
            args.top_n,
        ),
        "skew_bucket": build_segment_summaries(
            closed_records,
            lambda row: skew_bucket(row.get("skew_ratio", "")),
            args.top_n,
        ),
    }

    symbol_reason_totals = summarize_symbol_reasons(symbol_header, symbol_rows)
    candidate_reason_totals = summarize_candidate_reasons(candidate_rows)
    trend_rows = build_daily_rejection_trend(
        symbol_rows,
        candidate_rows,
        args.symbol_date_column,
        args.candidate_date_column,
    )

    reason_summary_rows = load_rejection_export(reason_summary_path, "reason")
    bucket_summary_rows = load_rejection_export(bucket_summary_path, "bucket")

    recommendation_lines = recommendations(overall, bucket_summary_rows, segment_rows)

    # Load ranking data and compute backtest if available
    ranking_rows = load_latest_rankings(args.reports_dir)
    ranking_backtest_results = build_ranking_quality_backtest(
        closed_trade_rows, ranking_rows
    )

    # Compute sensitivity analysis on rejection bottlenecks
    sensitivity_analysis_results = build_sensitivity_analysis(
        candidate_rows, symbol_rows
    )

    # Compute candidate-level ranking impact analysis
    candidate_ranking_impact_results = build_candidate_ranking_impact(
        candidate_rows, ranking_rows
    )
    recommendation_impact_rows = build_recommendation_impact_confidence(
        recommendation_lines,
        overall,
        sensitivity_analysis_results,
        candidate_ranking_impact_results,
    )

    now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    if start_date is None and end_date is None:
        window_text = "all dates"
    else:
        window_text = (
            f"{start_date.isoformat() if start_date else '-inf'} to "
            f"{end_date.isoformat() if end_date else '+inf'}"
        )

    file_suffix = (
        end_date.isoformat() if end_date else datetime.now().date().isoformat()
    )
    markdown_output_path = args.reports_dir / f"{args.output_prefix}_{file_suffix}.md"
    csv_output_path = args.reports_dir / f"{args.output_prefix}_{file_suffix}.csv"

    report_text = build_markdown_report(
        window_text=window_text,
        generated_at=now,
        total_rows=len(analysis_rows),
        selected_rows=len(selected_rows),
        closed_records=closed_records,
        overall=overall,
        rolling_window_metrics=rolling_window_metrics,
        rolling_rejection_trends=rolling_rejection_trends,
        rolling_rejection_reason_trends=rolling_rejection_reason_trends,
        ranking_backtest_results=ranking_backtest_results,
        sensitivity_analysis_results=sensitivity_analysis_results,
        candidate_ranking_impact_results=candidate_ranking_impact_results,
        segment_rows=segment_rows,
        symbol_reason_totals=symbol_reason_totals,
        candidate_reason_totals=candidate_reason_totals,
        trend_rows=trend_rows,
        reason_summary_rows=reason_summary_rows,
        bucket_summary_rows=bucket_summary_rows,
        recommendation_lines=recommendation_lines,
        recommendation_impact_rows=recommendation_impact_rows,
        markdown_output_path=markdown_output_path,
        csv_output_path=csv_output_path,
    )

    markdown_output_path.parent.mkdir(parents=True, exist_ok=True)
